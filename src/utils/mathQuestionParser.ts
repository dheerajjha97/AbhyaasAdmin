/**
 * Splits lines and detects questions specifically for Mathematics format.
 */
export function parseMathExamContent(
  rawText: string,
  meta: MathPaperMeta = {}
): ParsedPaperResult {
  const classId = meta.classId || 'class-10';
  const className = meta.className || 'Class 10';
  const subjectId = meta.subjectId || 'mathematics';
  const subjectName = meta.subjectName || 'Mathematics (गणित)';
  const board = meta.board || 'Bihar Board (BSEB Matric)';
  const year = meta.year || 2026;
  const set = meta.set || 'Set A';

  if (!rawText || !rawText.trim()) {
    return createEmptyMathResult({ classId, className, subjectId, subjectName, board, year, set });
  }

  // Pre-process lines
  const rawLines = rawText.split(/\r?\n/);

  let currentSectionId: 'sec-a' | 'sec-b' | 'sec-c' = 'sec-a';
  let currentSectionName = 'खण्ड-अ / SECTION-A (वस्तुनिष्ठ प्रश्न)';

  type RawBlock = {
    sectionId: 'sec-a' | 'sec-b' | 'sec-c';
    sectionName: string;
    rawQNum: number;
    lines: string[];
  };

  const blocks: RawBlock[] = [];
  let currentBlock: RawBlock | null = null;
  let inAnswerBlock = false;

  // Regex for section boundary
  const secARegex = /(?:खण्ड[\s\-–—]*अ|SECTION[\s\-–—]*A|वस्तुनिष्ठ\s*प्रश्न|OBJECTIVE\s*QUESTIONS)/i;
  const secBRegex = /(?:खण्ड[\s\-–—]*ब|SECTION[\s\-–—]*B|लघु\s*उत्तरीय\s*प्रश्न|SHORT\s*ANSWER\s*QUESTIONS)/i;
  const secCRegex = /(?:खण्ड[\s\-–—]*स|खण्ड[\s\-–—]*ग|SECTION[\s\-–—]*C|दीर्घ\s*उत्तरीय\s*प्रश्न|LONG\s*ANSWER\s*QUESTIONS)/i;

  // Question header regex for start of question:
  // e.g., "1. निम्नलिखित में...", "100. यदि वृत्त...", "31. रैखिक..."
  const qHeaderRegex = /^(\d{1,3})\s*[\.\:\-\–—\)]\s+(.*)$/;

  for (let i = 0; i < rawLines.length; i++) {
    const rawLine = rawLines[i];
    const trimmed = rawLine.trim();

    // Skip horizontal divider lines
    if (/^[=\-*#_~]{3,}$/.test(trimmed)) {
      continue;
    }

    // Check for Section headers
    if (secCRegex.test(trimmed) && (trimmed.includes('SECTION') || trimmed.includes('खण्ड') || trimmed.includes('दीर्घ'))) {
      currentSectionId = 'sec-c';
      currentSectionName = 'खण्ड-स / SECTION-C (दीर्घ उत्तरीय प्रश्न)';
      currentBlock = null;
      inAnswerBlock = false;
      continue;
    } else if (secBRegex.test(trimmed) && (trimmed.includes('SECTION') || trimmed.includes('खण्ड') || trimmed.includes('लघु'))) {
      currentSectionId = 'sec-b';
      currentSectionName = 'खण्ड-ब / SECTION-B (लघु उत्तरीय प्रश्न)';
      currentBlock = null;
      inAnswerBlock = false;
      continue;
    } else if (secARegex.test(trimmed) && (trimmed.includes('SECTION') || trimmed.includes('खण्ड') || trimmed.includes('वस्तुनिष्ठ'))) {
      currentSectionId = 'sec-a';
      currentSectionName = 'खण्ड-अ / SECTION-A (वस्तुनिष्ठ प्रश्न)';
      currentBlock = null;
      inAnswerBlock = false;
      continue;
    }

    if (!trimmed) {
      // blank line: if inside a block, we can still keep going
      continue;
    }

    // Check if line marks the start of "उत्तर:" or "हल:" or "व्याख्या:"
    if (/^(?:उत्तर|सही\s*उत्तर|हल|व्याख्या|Ans|Answer|Solution)\s*[:\-\=–—]/i.test(trimmed)) {
      inAnswerBlock = true;
    }

    // Match question number at start of line
    const match = trimmed.match(qHeaderRegex);

    // To prevent false positives inside derivation / solution steps:
    // E.g., inside answer: "(i) प्रथम...", "(I) दिया है...", "15² + 8² = 289...", "1. यदि x = 1..."
    // In math derivations, step numbers are usually indented or follow "उत्तर:" or have equation signs.
    let isNewQuestion = false;
    let detectedQNum = 0;

    if (match) {
      const num = parseInt(match[1], 10);
      const rest = match[2].trim();

      // Lines inside derivation / proof (e.g. "=> x = 2", "= (3/5)", "समीकरण (1) और (2)")
      const isDerivationStep = inAnswerBlock && /^(?:[xyzabchlnpmk]\s*=|\=\s*|=>|दोनों\s*पक्षों|अतः|चूँकि|समीकरण\s*\()/i.test(rest);
      const isIndented = rawLine.startsWith('    ') || rawLine.startsWith('\t');

      if (!isDerivationStep && !isIndented) {
        if (!currentBlock) {
          isNewQuestion = true;
          detectedQNum = num;
        } else {
          // Check question progression:
          if (num === currentBlock.rawQNum + 1 || (num > currentBlock.rawQNum && num <= currentBlock.rawQNum + 5)) {
            isNewQuestion = true;
            detectedQNum = num;
          }
        }
      }
    }

    if (isNewQuestion) {
      inAnswerBlock = false;
      currentBlock = {
        sectionId: currentSectionId,
        sectionName: currentSectionName,
        rawQNum: detectedQNum,
        lines: [trimmed],
      };
      blocks.push(currentBlock);
    } else {
      if (currentBlock) {
        currentBlock.lines.push(trimmed);
      }
    }
  }

  // Parse each block into a ParsedQuestion
  const questions: ParsedQuestion[] = [];
  let globalQNum = 1;

  for (let i = 0; i < blocks.length; i++) {
    const block = blocks[i];
    const q = parseSingleMathBlock(block, globalQNum);
    questions.push(q);
    globalQNum++;
  }

  const mcqCount = questions.filter(q => q.type === 'mcq').length;
  const shortCount = questions.filter(q => q.type === 'short').length;
  const longCount = questions.filter(q => q.type === 'long').length;

  const totalMarks = (mcqCount * 1) + (shortCount * 2) + (longCount * 5);

  return {
    paperId: `math-${classId}-${year}-${set.toLowerCase().replace(/\s+/g, '_')}`,
    title: `${className} ${subjectName} Board Model Paper ${year} (${set})`,
    classId,
    className,
    subjectId,
    subjectName,
    board,
    year,
    set,
    durationMinutes: 195, // 3 Hours 15 Minutes standard board exam
    totalMarks,
    rawQuestionsCount: questions.length,
    stats: {
      totalQuestions: questions.length,
      mcqCount,
      shortCount,
      longCount,
      answeredCount: questions.filter(q => q.correctAnswer || q.modelAnswer).length,
    },
    sections: [
      {
        id: 'sec-a',
        name: 'खण्ड-अ : वस्तुनिष्ठ प्रश्न (MCQ)',
        type: 'mcq',
        questionCount: mcqCount,
        marksPerQuestion: 1,
      },
      {
        id: 'sec-b',
        name: 'खण्ड-ब : लघु उत्तरीय प्रश्न (Short Answer)',
        type: 'short',
        questionCount: shortCount,
        marksPerQuestion: 2,
      },
      {
        id: 'sec-c',
        name: 'खण्ड-स : दीर्घ उत्तरीय प्रश्न (Long Answer)',
        type: 'long',
        questionCount: longCount,
        marksPerQuestion: 5,
      },
    ],
    questions,
  };
}

function parseSingleMathBlock(
  block: { sectionId: 'sec-a' | 'sec-b' | 'sec-c'; sectionName: string; rawQNum: number; lines: string[] },
  globalQNum: number
): ParsedQuestion {
  const fullText = block.lines.join('\n');
  const type: 'mcq' | 'short' | 'long' = block.sectionId === 'sec-a' ? 'mcq' : block.sectionId === 'sec-b' ? 'short' : 'long';
  const marks = type === 'mcq' ? 1 : type === 'short' ? 2 : 5;

  if (type === 'mcq') {
    return parseMathMCQ(block, globalQNum, marks);
  } else {
    return parseMathSubjective(block, globalQNum, type, marks);
  }
}

/**
 * Handles MCQ parsing for math questions with (A), (B), (C), (D) inline or multiline.
 */
function parseMathMCQ(
  block: { sectionId: 'sec-a' | 'sec-b' | 'sec-c'; sectionName: string; rawQNum: number; lines: string[] },
  globalQNum: number,
  marks: number
): ParsedQuestion {
  const allLines = [...block.lines];
  let promptLines: string[] = [];
  let answerLine = '';
  let explanationLines: string[] = [];

  for (let i = 0; i < allLines.length; i++) {
    const line = allLines[i];
    if (/^(?:सही\s*उत्तर|उत्तर|Ans|Answer)\s*[:\-\=–—]/i.test(line)) {
      answerLine = line;
    } else if (/^(?:व्याख्या|Explanation|हल|Solution)\s*[:\-\=–—]/i.test(line)) {
      explanationLines = allLines.slice(i);
      break;
    } else if (!answerLine) {
      promptLines.push(line);
    }
  }

  const promptAndOptionsText = promptLines.join(' ');

  // Clean initial "1. " or "2. " from question prompt
  const cleanPrompt = promptAndOptionsText.replace(/^\d{1,3}\s*[\.\:\-\–—\)]\s*/, '').trim();

  // Extract Options (A), (B), (C), (D) or (क), (ख), (ग), (घ) with robust tokenization
  // Prevents math formulas (e.g. (a, b), (l + b)h, tan² A, c - d) from being mistaken as option keys
  const markerRegex = /(?:^|[\s\t\n]+)(?:\(([ABCDकखगघ])\)|\[([ABCDकखगघ])\]|(?:^|[\n\r]+|[;\t]|\s{2,})([ABCDकखगघ])[\.\)]\s*|(?:^|[\s\t\n]+)([ABCDकखगघ])\.\s*)/g;
  const keyMap: Record<string, 'A' | 'B' | 'C' | 'D'> = {
    A: 'A', a: 'A', 'क': 'A',
    B: 'B', b: 'B', 'ख': 'B',
    C: 'C', c: 'C', 'ग': 'C',
    D: 'D', d: 'D', 'घ': 'D',
  };

  interface OptionHit {
    key: 'A' | 'B' | 'C' | 'D';
    startIndex: number;
    textStartIndex: number;
  }

  const matches: OptionHit[] = [];
  let match: RegExpExecArray | null;

  while ((match = markerRegex.exec(cleanPrompt)) !== null) {
    const rawKey = match[1] || match[2] || match[3] || match[4];
    if (!rawKey) continue;
    const standardKey = keyMap[rawKey];
    if (!standardKey) continue;
    const matchStr = match[0];
    const leadingWhitespaceLen = matchStr.match(/^[\s\t\n]+/)?.[0].length || 0;
    const actualStartIndex = match.index + leadingWhitespaceLen;
    const textStartIndex = match.index + matchStr.length;
    matches.push({
      key: standardKey,
      startIndex: actualStartIndex,
      textStartIndex,
    });
  }

  // Deduplicate keys: keep only the first valid occurrence of each key A, B, C, D
  const validHits: OptionHit[] = [];
  const usedKeys = new Set<'A' | 'B' | 'C' | 'D'>();
  for (const hit of matches) {
    if (!usedKeys.has(hit.key)) {
      usedKeys.add(hit.key);
      validHits.push(hit);
    }
  }

  let questionText = cleanPrompt;
  const options: ParsedOption[] = [];

  if (validHits.length > 0) {
    questionText = cleanPrompt.substring(0, validHits[0].startIndex).trim();
    for (let i = 0; i < validHits.length; i++) {
      const cur = validHits[i];
      const next = validHits[i + 1];
      let optText = (next ? cleanPrompt.substring(cur.textStartIndex, next.startIndex) : cleanPrompt.substring(cur.textStartIndex)).trim();
      optText = optText.replace(/(?:सही\s*उत्तर|उत्तर|Ans|Answer)\s*[:\-\=–—\s]*.*$/i, '').trim();
      options.push({
        id: `opt-${globalQNum}-${cur.key}`,
        key: cur.key,
        text: optText,
      });
    }
  }

  // Parse correct answer
  let correctAnswer: string | undefined = undefined;
  let correctAnswerText: string | undefined = undefined;

  if (answerLine) {
    const ansMatch = answerLine.match(/(?:सही\s*उत्तर|उत्तर|Ans|Answer)\s*[:\-\=–—\s]+\(?([ABCDकखगघ])\)?(?:\s+(.*))?/i);
    if (ansMatch) {
      correctAnswer = keyMap[ansMatch[1]] || ansMatch[1].toUpperCase();
      correctAnswerText = ansMatch[2] ? `(${correctAnswer}) ${ansMatch[2].trim()}` : `(${correctAnswer})`;
    } else {
      correctAnswerText = answerLine.replace(/^(?:सही\s*उत्तर|उत्तर|Ans|Answer)\s*[:\-\=–—\s]*/i, '').trim();
    }
  }

  // Parse explanation
  let explanation: string | undefined = undefined;
  if (explanationLines.length > 0) {
    explanation = explanationLines
      .join('\n')
      .replace(/^(?:व्याख्या|Explanation|हल|Solution)\s*[:\-\=–—\s]*/i, '')
      .trim();
  }

  return {
    id: `math-q-${globalQNum}`,
    sectionId: block.sectionId,
    sectionName: block.sectionName,
    questionNumber: block.rawQNum,
    type: 'mcq',
    text: questionText,
    options: options.length > 0 ? options : undefined,
    correctAnswer,
    correctAnswerText,
    explanation,
    marks,
  };
}

/**
 * Handles Subjective (Short & Long) math question parsing.
 */
function parseMathSubjective(
  block: { sectionId: 'sec-a' | 'sec-b' | 'sec-c'; sectionName: string; rawQNum: number; lines: string[] },
  globalQNum: number,
  type: 'short' | 'long',
  marks: number
): ParsedQuestion {
  const allLines = [...block.lines];
  let qLines: string[] = [];
  let ansLines: string[] = [];
  let foundAnsMarker = false;

  for (let i = 0; i < allLines.length; i++) {
    const line = allLines[i];
    if (/^(?:उत्तर|हल|Solution|Ans|Answer|प्रमाण|Proof)\s*[:\-\=–—]/i.test(line)) {
      foundAnsMarker = true;
      const stripped = line.replace(/^(?:उत्तर|हल|Solution|Ans|Answer|प्रमाण|Proof)\s*[:\-\=–—\s]*/i, '').trim();
      if (stripped) {
        ansLines.push(stripped);
      }
    } else if (foundAnsMarker) {
      ansLines.push(line);
    } else {
      qLines.push(line);
    }
  }

  // Question Prompt
  let rawPrompt = qLines.join('\n').replace(/^\d{1,3}\s*[\.\:\-\–—\)]\s*/, '').trim();
  
  // Model Answer
  const modelAnswer = ansLines.join('\n').trim();

  return {
    id: `math-q-${globalQNum}`,
    sectionId: block.sectionId,
    sectionName: block.sectionName,
    questionNumber: block.rawQNum,
    type,
    text: rawPrompt || `प्रश्न ${block.rawQNum}`,
    modelAnswer: modelAnswer || undefined,
    marks,
  };
}

function createEmptyMathResult(meta: MathPaperMeta): ParsedPaperResult {
  return {
    paperId: `math-${meta.classId}-${meta.year}-empty`,
    title: `${meta.className} ${meta.subjectName} Model Paper ${meta.year}`,
    classId: meta.classId || 'class-10',
    className: meta.className || 'Class 10',
    subjectId: meta.subjectId || 'mathematics',
    subjectName: meta.subjectName || 'Mathematics',
    board: meta.board || 'BSEB',
    year: meta.year || 2026,
    set: meta.set || 'Set A',
    durationMinutes: 195,
    totalMarks: 0,
    rawQuestionsCount: 0,
    stats: {
      totalQuestions: 0,
      mcqCount: 0,
      shortCount: 0,
      longCount: 0,
      answeredCount: 0,
    },
    sections: [],
    questions: [],
  };
}
